def bi(vi, en, tag="span"):
    """Inline bilingual text."""
    if vi == en:
        return html.escape(vi)
    return f'<{tag} class="l-vi">{html.escape(vi)}</{tag}><{tag} class="l-en" lang="en">{html.escape(en)}</{tag}>'


def bi_html(vi, en, tag="span"):
    return f'<{tag} class="l-vi">{vi}</{tag}><{tag} class="l-en" lang="en">{en}</{tag}>'


