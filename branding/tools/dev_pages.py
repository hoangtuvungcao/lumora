def package_files():
    """Build sdk/dist (wheel, sdist, npm tarball) when missing or stale, return the files."""
    dist = SDK / "dist"
    version = re.search(r'^__version__ = "([^"]+)"', (SDK / "python" / "lumora_bot.py").read_text(encoding="utf-8"), re.M).group(1)
    want = [f"lumora_bot-{version}-py3-none-any.whl", f"lumora-bot-{version}.tgz"]
    newest_src = max(p.stat().st_mtime for p in [SDK / "python" / "lumora_bot.py", SDK / "js" / "lumora-bot.mjs", SDK / "js" / "lumora-bot.d.ts",
                                                  SDK / "CHANGELOG.md"])
    if not all((dist / w).exists() and (dist / w).stat().st_mtime >= newest_src for w in want):
        try:
            subprocess.run([sys.executable, str(SDK / "tools" / "package.py")], check=True, stdout=subprocess.DEVNULL)
        except (subprocess.CalledProcessError, OSError) as e:
            raise SystemExit(f"could not build the SDK packages ({e}); run: pip install build setuptools && python3 sdk/tools/package.py")
    return version, [dist / w for w in want] + sorted(p for p in dist.glob("*.tar.gz"))


def copy_sdk():
    dst = DEV / "sdk"
    if dst.exists():
        shutil.rmtree(dst)
    for rel, s in SDK_FILES.items():
        (dst / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(s, dst / rel)
    (dst / "examples").mkdir(parents=True, exist_ok=True)
    for _, py, js, *_ in EXAMPLES:
        for f in (py, js):
            shutil.copyfile(SDK / "examples" / f, dst / "examples" / f)
    for f, _ in SMALL_EXAMPLES:
        shutil.copyfile(SDK / "examples" / f, dst / "examples" / f)
    shutil.copyfile(SDK / "LICENSE", dst / "LICENSE.txt")
    version, pkgs = package_files()
    pdst = DEV / "packages"
    if pdst.exists():
        shutil.rmtree(pdst)
    pdst.mkdir(parents=True)
    for p in pkgs:
        shutil.copyfile(p, pdst / p.name)
    return version


