def _include(text, base):
    def sub(m):
        spec = m.group(1).strip()
        parts = spec.split(":")
        path = (base / parts[0]).resolve()
        lines = path.read_text(encoding="utf-8").splitlines()
        start = int(parts[1]) if len(parts) > 1 and parts[1] else 1
        end = int(parts[2]) if len(parts) > 2 and parts[2] else len(lines)
        out = []
        for ln in lines[start - 1:end]:
            out.append("#" + ln if ln.startswith("#") else ln)
        return "\n".join(out)
    return re.sub(r"\{\{#include\s+([^}]+)\}\}", sub, text)


def _code_html(code, lang):
    dl = LANG_MAP.get(lang.lower(), "text")
    return f'<pre class="code"><code data-lang="{dl}">{html.escape(code.rstrip())}</code></pre>'


FENCE = re.compile(r"^```([\w-]*)[^\n]*\n(.*?)^```[ \t]*$", re.M | re.S)


def _tabs(blocks):
    n = next(_ids)
    btns, panels = [], []
    for i, (lang, code) in enumerate(blocks):
        label, key = TAB_LABEL[lang]
        tid, pid = f"tab-{n}-{i}", f"panel-{n}-{i}"
        btns.append(f'<button type="button" role="tab" aria-selected="{"true" if i == 0 else "false"}" id="{tid}" '
                    f'aria-controls="{pid}" data-sync="{key}">{label}</button>')
        panels.append(f'<div role="tabpanel" id="{pid}" aria-labelledby="{tid}" class="tabs__panel">{_code_html(code, lang)}</div>')
    return f'<div class="tabs tabs--code glass" data-tabs><div class="tabs__list" role="tablist">{"".join(btns)}</div>{"".join(panels)}</div>'


def md_html(text, *, toc_ids=False):
    """Markdown → HTML in the site's style (code blocks, tables, tabs)."""
    stash = {}

    def keep(h):
        k = f"\u0000STASH{len(stash)}\u0000"
        stash[k] = h
        return f"\n\n{k}\n\n"

    # group consecutive fenced blocks into tabs when they are language alternatives
    out, pos = [], 0
    ms = list(FENCE.finditer(text))
    i = 0
    while i < len(ms):
        j = i
        while j + 1 < len(ms) and not text[ms[j].end():ms[j + 1].start()].strip():
            j += 1
        group = ms[i:j + 1]
        langs = [m.group(1).lower() for m in group]
        out.append(text[pos:group[0].start()])
        if len(group) > 1 and any(set(langs) == s and len(langs) == len(s) for s in TAB_SETS):
            out.append(keep(_tabs([(m.group(1).lower(), m.group(2)) for m in group])))
        else:
            for k, m in enumerate(group):
                if k:
                    out.append("\n")
                out.append(keep(_code_html(m.group(2), m.group(1))))
        pos = group[-1].end()
        i = j + 1
    out.append(text[pos:])
    body = markdown.markdown("".join(out), extensions=["tables", "attr_list"] + (["toc"] if toc_ids else []),
                             extension_configs={"toc": {"permalink": False}} if toc_ids else {})
    for k, v in stash.items():
        body = body.replace(f"<p>{k}</p>", v).replace(k, v)
    body = body.replace("\\|", "|")
    body = body.replace("<table>", '<div class="table-wrap"><table class="table table--api">').replace("</table>", "</table></div>")
    return body


def parse_bilingual(path):
    """→ (title_vi, title_en, [(id, vi, en, html)])."""
    src = path.read_text(encoding="utf-8")
    src = re.sub(r"<!--(?!\s*(?:section:|vi\s*-->|en\s*-->|all\s*-->)).*?-->", "", src, flags=re.S)
    src = _include(src, path.parent)
    m = re.match(r"\s*# (.+?) \| (.+?)\n", src)
    title = (m.group(1).strip(), m.group(2).strip()) if m else ("", "")
    sections = []
    for sm in re.finditer(r"<!--\s*section:\s*([\w-]+)\s*-->\s*\n## (.+?) \| (.+?)\n(.*?)(?=<!--\s*section:|\Z)", src, re.S):
        sid, tvi, ten, body = sm.group(1), sm.group(2).strip(), sm.group(3).strip(), sm.group(4)
        chunks = re.split(r"<!--\s*(vi|en|all)\s*-->", body)
        parts = []
        if chunks[0].strip():
            parts.append(("all", chunks[0]))
        for k in range(1, len(chunks), 2):
            parts.append((chunks[k], chunks[k + 1]))
        h = []
        for lang, text in parts:
            if not text.strip():
                continue
            inner = md_html(text)
            if lang == "all":
                h.append(inner)
            else:
                attr = ' lang="en"' if lang == "en" else ""
                h.append(f'<div class="l-{lang}"{attr}>{inner}</div>')
        sections.append((sid, tvi, ten, "\n".join(h)))
    return title, sections


