"""Regenerate src/api_args.rs: the argument names each api.rs command reads.
Run: python3 -I core/fuzz/tools/gen_api_args.py   (after changing core/crates/lumora-core/src/api.rs)"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
api = (root / "../crates/lumora-core/src/api.rs").read_text()
body = api[api.index("async fn dispatch"):]
arms = re.split(r'\n        ("[a-z_]+"(?:\s*\|\s*"[a-z_]+")*) =>', body)
out = {}
for i in range(1, len(arms) - 1, 2):
    names = re.findall(r'"([a-z_]+)"', arms[i])
    keys = re.findall(r'(?:\bs|\bb|id16|strs|peer|\.get)\(\s*(?:r,\s*)?"([a-z_]+)"', arms[i + 1])
    keys = list(dict.fromkeys(k for k in keys if k != "cmd"))
    for n in names:
        out[n] = keys
lines = ["// @generated by tools/gen_api_args.py from lumora-core/src/api.rs — do not edit.",
         "pub const API_ARGS: &[(&str, &[&str])] = &["]
for n, ks in sorted(out.items()):
    lines.append(f'    ("{n}", &[{", ".join(chr(34) + k + chr(34) for k in ks)}]),')
lines.append("];")
(root / "src/api_args.rs").write_text("\n".join(lines) + "\n")
print(len(out), "commands")
