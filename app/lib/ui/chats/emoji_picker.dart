/// Section header height in the emoji grid.
const double _kHeader = 30;

/// Grid side padding.
const double _kPad = 8;

/// Columns for a picker [width]: 8 on phones, 9-10 on desktop, cells >= 44px.
int emojiColumns(double width, {required bool desktop}) {
  final fit = ((width - 2 * _kPad) / 44).floor();
  final want = desktop ? (width >= 440 ? 10 : 9) : (width >= 560 ? 10 : 8);
  return want.clamp(5, fit < 5 ? 5 : fit);
}

// Category tab icons: Phosphor (regular, filled when selected), matching
// AppIcons. TODO(icons): move these into AppIcons (emojiPeople, emojiFood...)
