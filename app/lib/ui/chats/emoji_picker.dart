const _kGroupIcons = <String, (IconData, IconData)>{
  'emoji_smileys': (PhosphorIconsRegular.smiley, PhosphorIconsFill.smiley),
  'emoji_people': (PhosphorIconsRegular.handWaving, PhosphorIconsFill.handWaving),
  'emoji_animals': (PhosphorIconsRegular.pawPrint, PhosphorIconsFill.pawPrint),
  'emoji_food': (PhosphorIconsRegular.bowlSteam, PhosphorIconsFill.bowlSteam),
  'emoji_travel': (PhosphorIconsRegular.airplaneTilt, PhosphorIconsFill.airplaneTilt),
  'emoji_activity': (PhosphorIconsRegular.soccerBall, PhosphorIconsFill.soccerBall),
  'emoji_objects': (PhosphorIconsRegular.lightbulb, PhosphorIconsFill.lightbulb),
  'emoji_symbols': (PhosphorIconsRegular.heart, PhosphorIconsFill.heart),
  'emoji_flags': (PhosphorIconsRegular.flag, PhosphorIconsFill.flag),
};

/// One cell: what gets inserted ([char], with the skin tone applied) and the
/// catalog entry behind it (null for unknown recents).
class _Item {
  const _Item(this.char, this.base);
  final String char;
  final Emoji? base;
}

class _Section {
  _Section(this.key, this.items, this.tab);
  final String key; // l10n key
  final List<_Item> items;
  final int tab;
}

/// Categorised emoji picker (Unicode 15.1) with search (vi/en, diacritics
/// optional), recently / frequently used, skin tones, keyboard navigation,
/// and - optionally - stickers and GIF tabs.
class EmojiPicker extends StatefulWidget {
  const EmojiPicker({
    super.key,
    required this.onPick,
    this.height = 300,
    this.showStickers = true,
    this.onSticker,
    this.onCustomSticker,
    this.onGif,
    this.autofocusSearch = false,
  });

  /// Sends a sticker from my packs.
  final void Function(Sticker s)? onCustomSticker;

  /// Sends a GIF picked from files (plays inline).
  final VoidCallback? onGif;
  final ValueChanged<String> onPick;

  /// Sends a sticker immediately (stickers tab hidden when null).
  final ValueChanged<String>? onSticker;
  final double height;
  final bool showStickers;

  /// Focus the search field on open (popover / dialog; not the inline panel,
  /// where the message field keeps focus).
  final bool autofocusSearch;

  @override
  State<EmojiPicker> createState() => _EmojiPickerState();
}

class _EmojiPickerState extends State<EmojiPicker> {
  late final EmojiCatalog _catalog = EmojiCatalog.instance;
  final _scroll = ScrollController();
  final _query = TextEditingController();
  final _searchFocus = FocusNode(debugLabel: 'emoji-search');
  final _gridFocus = FocusNode(debugLabel: 'emoji-grid');

  /// Hovered (mouse) or keyboard-selected cell, shown in the preview bar.
  final _preview = ValueNotifier<_Item?>(null);

  /// Keyboard cursor (index into [_flat]), -1 = none.
  final _cursor = ValueNotifier<int>(-1);

  int _tab = 0; // 0 = recent, 1..9 groups, then stickers, GIF
  bool _jumping = false;
  List<_Section> _sections = const [];
  List<_Item> _flat = const [];
  List<double> _starts = const []; // scroll offset of each section
  int _cols = 8;
  double _cell = 44;
  String _builtFor = '';
  OverlayEntry? _peek;

  int get _stickersTab => _catalog.groups.length + 1;
  int get _gifTab => _catalog.groups.length + 2;
  bool get _searching => _query.text.trim().isNotEmpty;

  @override
  void initState() {
    super.initState();
    _scroll.addListener(_syncTab);
    _query.addListener(_onQuery);
    // Build the search index after the first frame so typing is instant.
    WidgetsBinding.instance.addPostFrameCallback((_) => Future.microtask(_catalog.warmUpSearch));
  }

  @override
  void dispose() {
    _hidePeek();
    _scroll.dispose();
    _query.dispose();
    _searchFocus.dispose();
    _gridFocus.dispose();
    _preview.dispose();
    _cursor.dispose();
    super.dispose();
  }

  void _onQuery() {
    _cursor.value = -1;
    if (_scroll.hasClients) _scroll.jumpTo(0);
    setState(() {});
  }

  // ---------------------------------------------------------------- data

  List<_Item> _recentItems(Settings st) {
    final List<String> list;
    if (st.emojiFrequentFirst && st.emojiUsage.isNotEmpty) {
      final seen = <String>{};
      final byUse = st.emojiUsage.entries.toList()
        ..sort((a, b) {
          final c = b.value.compareTo(a.value);
          if (c != 0) return c;
          final ia = st.recentEmojis.indexOf(a.key), ib = st.recentEmojis.indexOf(b.key);
          return (ia < 0 ? 999 : ia).compareTo(ib < 0 ? 999 : ib);
        });
      list = [
        for (final e in [...byUse.map((x) => x.key), ...st.recentEmojis])
          if (seen.add(e)) e,
      ].take(kRecentEmojiMax).toList();
    } else {
      list = st.recentEmojis.take(kRecentEmojiMax).toList();
    }
    return [for (final e in list) _Item(e, _catalog.lookup(e))];
  }

  void _rebuildSections(Settings st) {
    final key = '${_query.text}|${st.emojiTone}|${st.emojiFrequentFirst}|${st.recentEmojis.join()}';
    if (key == _builtFor) return;
    _builtFor = key;
    final tone = st.emojiTone;
    if (_searching) {
      final res = _catalog.search(_query.text, usage: st.emojiUsage);
      _sections = [
        _Section('emoji_results', [for (final e in res) _Item(e.withTone(tone), e)], 0),
      ];
    } else {
      _sections = [
        _Section('emoji_recent', _recentItems(st), 0),
        for (var g = 0; g < _catalog.groups.length; g++)
          _Section(_catalog.groups[g].key, [for (final e in _catalog.groups[g].emojis) _Item(e.withTone(tone), e)], g + 1),
      ];
    }
    _flat = [for (final s in _sections) ...s.items];
  }

  void _layout(double width, bool desktop) {
    _cols = emojiColumns(width, desktop: desktop);
    _cell = (width - 2 * _kPad) / _cols;
    var y = 0.0;
    _starts = [
      for (final s in _sections)
        () {
          final at = y;
          // An empty "recent" section still shows one row (a hint).
          y += _kHeader + (s.items.isEmpty ? 1 : (s.items.length / _cols).ceil()) * _cell;
          return at;
        }(),
    ];
  }

  // ---------------------------------------------------------------- tabs

  void _syncTab() {
    if (_jumping || _searching || !_scroll.hasClients || _starts.isEmpty) return;
    final y = _scroll.offset + 8;
    var i = 0;
    while (i + 1 < _starts.length && _starts[i + 1] <= y) {
      i++;
    }
    // At the very bottom the last (short) section can never reach the top.
    if (_scroll.position.pixels >= _scroll.position.maxScrollExtent - 1) i = _starts.length - 1;
    final tab = _sections[i].tab;
    if (tab != _tab) setState(() => _tab = tab);
  }

  Future<void> _openTab(int tab) async {
    if (tab >= _stickersTab) {
      setState(() => _tab = tab);
      return;
    }
    if (_searching) _query.clear();
    final wasEmojiTab = _tab < _stickersTab;
    setState(() => _tab = tab);
    if (!wasEmojiTab) return; // the grid is rebuilt at the top; jump after layout
    final i = _sections.indexWhere((s) => s.tab == tab);
    if (i < 0 || !_scroll.hasClients) return;
    final target = _starts[i].clamp(0.0, _scroll.position.maxScrollExtent);
    _jumping = true;
    try {
      final far = (target - _scroll.offset).abs() > 2400;
      if (far) {
        _scroll.jumpTo(target);
      } else {
        await _scroll.animateTo(target, duration: Motion.slow, curve: Motion.curve);
      }
    } finally {
      _jumping = false;
    }
  }

  // ---------------------------------------------------------------- picking

  void _pick(String e) {
    context.read<Settings>().pushRecentEmoji(e);
    HapticFeedback.selectionClick();
    widget.onPick(e);
  }

  Future<void> _chooseTone(_Item it, Rect anchor) async {
    final base = it.base;
    if (base == null || !base.tones) return;
    final st = context.read<Settings>();
    final tone = await showSkinTonePicker(context, base: base, anchor: anchor, current: EmojiCatalog.toneOf(it.char));
    if (tone == null || !mounted) return;
    st.update((s) => s.emojiTone = tone);
    _pick(base.withTone(tone));
  }

  void _showPeek(_Item it, Rect anchor) {
    _hidePeek();
    final overlay = Overlay.maybeOf(context, rootOverlay: true);
    if (overlay == null) return;
    final vi = S.read(context).vi;
    final name = it.base == null ? '' : _catalog.nameOf(it.base!, vi: vi);
    _peek = OverlayEntry(
      builder: (c) => _PeekBubble(anchor: anchor, emoji: it.char, name: name),
    );
    overlay.insert(_peek!);
  }

  void _hidePeek() {
    _peek?.remove();
    _peek = null;
  }

  // ---------------------------------------------------------------- keyboard

  KeyEventResult _onGridKey(FocusNode node, KeyEvent e) {
    if (e is! KeyDownEvent && e is! KeyRepeatEvent) return KeyEventResult.ignored;
    final k = e.logicalKey;
    final n = _flat.length;
    if (n == 0) return KeyEventResult.ignored;
    var i = _cursor.value < 0 ? 0 : _cursor.value;
    if (k == LogicalKeyboardKey.arrowRight) {
      i = (i + 1).clamp(0, n - 1);
    } else if (k == LogicalKeyboardKey.arrowLeft) {
      i = (i - 1).clamp(0, n - 1);
    } else if (k == LogicalKeyboardKey.arrowDown) {
      i = _vertical(i, 1);
    } else if (k == LogicalKeyboardKey.arrowUp) {
      if (_rowOf(i) == (0, 0)) {
        _searchFocus.requestFocus();
        _cursor.value = -1;
        return KeyEventResult.handled;
      }
      i = _vertical(i, -1);
    } else if (k == LogicalKeyboardKey.home) {
      i = 0;
    } else if (k == LogicalKeyboardKey.end) {
      i = n - 1;
    } else if (k == LogicalKeyboardKey.enter || k == LogicalKeyboardKey.numpadEnter || k == LogicalKeyboardKey.space) {
      if (_cursor.value >= 0) _pick(_flat[_cursor.value].char);
      return KeyEventResult.handled;
    } else if (k == LogicalKeyboardKey.escape) {
      if (_searching) {
        _query.clear();
        return KeyEventResult.handled;
      }
      return KeyEventResult.ignored;
    } else if (e.character != null &&
        e.character!.trim().isNotEmpty &&
        !HardwareKeyboard.instance.isControlPressed &&
        !HardwareKeyboard.instance.isMetaPressed) {
      // Typing jumps to search.
      _searchFocus.requestFocus();
      _query.text += e.character!;
      _query.selection = TextSelection.collapsed(offset: _query.text.length);
      return KeyEventResult.handled;
    } else {
      return KeyEventResult.ignored;
    }
    _moveCursor(i);
    return KeyEventResult.handled;
  }

  /// (section, row-in-section) of flat index [i].
  (int, int) _rowOf(int i) {
    var base = 0;
    for (var s = 0; s < _sections.length; s++) {
      final len = _sections[s].items.length;
      if (i < base + len) return (s, (i - base) ~/ _cols);
      base += len;
    }
    return (_sections.length - 1, 0);
  }

  int _vertical(int i, int dir) {
    var base = 0;
    for (var s = 0; s < _sections.length; s++) {
      final len = _sections[s].items.length;
      if (i < base + len) {
        final local = i - base;
        final col = local % _cols;
        final target = local + dir * _cols;
        if (target >= 0 && target < len) return base + target;
        if (dir > 0) {
          // Last row of this section: same column in the next non-empty section.
          if ((len - 1) ~/ _cols > local ~/ _cols) return base + len - 1;
          var nb = base + len;
          for (var t = s + 1; t < _sections.length; t++) {
            final l2 = _sections[t].items.length;
            if (l2 > 0) return nb + (col < l2 ? col : l2 - 1);
            nb += l2;
          }
          return i;
        } else {
          var pb = base;
          for (var t = s - 1; t >= 0; t--) {
            final l2 = _sections[t].items.length;
            pb -= l2;
            if (l2 > 0) {
              final lastRow = (l2 - 1) ~/ _cols;
              final j = lastRow * _cols + col;
              return pb + (j < l2 ? j : l2 - 1);
            }
          }
          return i;
        }
      }
      base += len;
    }
    return i;
  }

  void _moveCursor(int i) {
    _cursor.value = i;
    _preview.value = _flat[i];
    // Keep it on screen.
    final (s, row) = _rowOf(i);
    if (!_scroll.hasClients || s >= _starts.length) return;
    final top = _starts[s] + _kHeader + row * _cell;
    final view = _scroll.position.viewportDimension;
    final off = _scroll.offset;
    if (top < off) {
      _scroll.jumpTo((top - _kHeader).clamp(0.0, _scroll.position.maxScrollExtent));
    } else if (top + _cell > off + view) {
      _scroll.jumpTo((top + _cell - view).clamp(0.0, _scroll.position.maxScrollExtent));
    }
  }

  KeyEventResult _onSearchKey(FocusNode node, KeyEvent e) {
    if (e is! KeyDownEvent) return KeyEventResult.ignored;
    if (e.logicalKey == LogicalKeyboardKey.arrowDown && _flat.isNotEmpty) {
      _gridFocus.requestFocus();
      _moveCursor(0);
      return KeyEventResult.handled;
    }
    if ((e.logicalKey == LogicalKeyboardKey.enter || e.logicalKey == LogicalKeyboardKey.numpadEnter) && _searching && _flat.isNotEmpty) {
      _pick(_flat.first.char);
      return KeyEventResult.handled;
    }
    if (e.logicalKey == LogicalKeyboardKey.escape && _searching) {
      _query.clear();
      return KeyEventResult.handled;
    }
    return KeyEventResult.ignored;
  }

  // ---------------------------------------------------------------- build

  @override
  Widget build(BuildContext context) {
    final s = S.of(context);
    final st = context.watch<Settings>();
    final desktop = isDesktop(context);
    _rebuildSections(st);
    final emojiTab = _tab < _stickersTab;
    return SizedBox(
      height: widget.height,
      child: Column(
        children: [
          if (emojiTab) _searchBar(s),
          _tabBar(s),
          Divider(height: 1, color: context.lc.divider),
          Expanded(
            child: _tab == _gifTab
                ? _gifPane(s)
                : _tab == _stickersTab
                ? _stickerPane()
                : LayoutBuilder(
                    builder: (context, c) {
                      _layout(c.maxWidth, desktop);
                      return _grid(s, st);
                    },
                  ),
          ),
          if (emojiTab && desktop) _PreviewBar(preview: _preview, catalog: _catalog, vi: s.vi, tone: st.emojiTone, onTone: _toneFromBar),
        ],
      ),
    );
  }

  Future<void> _toneFromBar(Rect anchor) async {
    final st = context.read<Settings>();
    final hand = _catalog.lookup('✋');
    if (hand == null) return;
    final t = await showSkinTonePicker(context, base: hand, anchor: anchor, current: st.emojiTone);
    if (t != null) st.update((x) => x.emojiTone = t);
  }

  Widget _searchBar(S s) {
    return Padding(
      padding: const EdgeInsets.fromLTRB(_kPad, 8, _kPad, 6),
      child: Focus(
        onKeyEvent: _onSearchKey,
        canRequestFocus: false,
        skipTraversal: true,
        child: SizedBox(
          height: 36,
          child: TextField(
            controller: _query,
            focusNode: _searchFocus,
            autofocus: widget.autofocusSearch,
            textInputAction: TextInputAction.search,
            style: const TextStyle(fontSize: 14),
            decoration: InputDecoration(
              isDense: true,
              hintText: s('emoji_search_hint'),
              prefixIcon: Icon(AppIcons.search, size: 18, color: context.lc.muted),
              prefixIconConstraints: const BoxConstraints(minWidth: 36, minHeight: 36),
              suffixIcon: _searching ? IconButton(tooltip: s('emoji_clear_search'), icon: const Icon(AppIcons.close, size: 16), onPressed: _query.clear) : null,
              contentPadding: const EdgeInsets.symmetric(vertical: 8),
              filled: true,
              fillColor: context.lc.surface2,
              border: OutlineInputBorder(borderRadius: BorderRadius.circular(Radii.md), borderSide: BorderSide.none),
              enabledBorder: OutlineInputBorder(borderRadius: BorderRadius.circular(Radii.md), borderSide: BorderSide.none),
              focusedBorder: OutlineInputBorder(
                borderRadius: BorderRadius.circular(Radii.md),
                borderSide: BorderSide(color: LC.primary.withValues(alpha: 0.6)),
              ),
            ),
          ),
        ),
      ),
    );
  }

  Widget _tabBar(S s) {
    final groups = _catalog.groups;
    final sel = _searching ? -1 : _tab;
    return SizedBox(
      height: 40,
      child: LayoutBuilder(
        builder: (context, c) {
          // Shrink tabs (down to 28 px) so every one fits on a phone.
          final n = groups.length + 1 + (widget.showStickers ? 2 : 0);
          final w = ((c.maxWidth - 12 - (widget.showStickers ? 9 : 0)) / n - 2).clamp(28.0, 36.0);
          Widget tab(int i, String tip, IconData icon, IconData selIcon) =>
              _TabIcon(selected: sel == i, tooltip: tip, onTap: () => _openTab(i), icon: icon, selectedIcon: selIcon, width: w);
          return ListView(
            scrollDirection: Axis.horizontal,
            padding: const EdgeInsets.symmetric(horizontal: 6),
            children: [
              tab(0, s('emoji_recent'), AppIcons.history, AppIcons.fill(AppIcons.history)),
              for (var i = 0; i < groups.length; i++)
                tab(
                  i + 1,
                  s(groups[i].key),
                  (_kGroupIcons[groups[i].key] ?? (AppIcons.emoji, AppIcons.emoji)).$1,
                  (_kGroupIcons[groups[i].key] ?? (AppIcons.emoji, AppIcons.emoji)).$2,
                ),
              if (widget.showStickers) ...[
                Center(
                  child: Container(width: 1, height: 20, margin: const EdgeInsets.symmetric(horizontal: 4), color: context.lc.divider),
                ),
                tab(_stickersTab, s('stickers'), AppIcons.sticker, AppIcons.fill(AppIcons.sticker)),
                tab(_gifTab, 'GIF', AppIcons.gif, AppIcons.fill(AppIcons.gif)),
              ],
            ],
          );
        },
      ),
    );
  }

  Widget _grid(S s, Settings st) {
    if (_searching && _flat.isEmpty) {
      return Center(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Icon(AppIcons.searchEmpty, size: 36, color: context.lc.muted),
            const SizedBox(height: 8),
            Text(s('emoji_no_results'), style: TextStyle(color: context.lc.muted)),
          ],
        ),
      );
    }
    final fontSize = (_cell * 0.62).clamp(22.0, 32.0);
    var base = 0;
    final slivers = <Widget>[];
    for (final sec in _sections) {
      final offset = base;
      base += sec.items.length;
      slivers.add(
        SliverToBoxAdapter(
          child: _SectionHeader(
            title: s(sec.key),
            trailing: sec.key == 'emoji_recent' && st.emojiUsage.isNotEmpty
                ? _RecentToggle(frequent: st.emojiFrequentFirst, onChanged: (v) => st.update((x) => x.emojiFrequentFirst = v))
                : null,
          ),
        ),
      );
      if (sec.items.isEmpty) {
        slivers.add(
          SliverToBoxAdapter(
            child: SizedBox(
              height: _cell,
              child: Center(
                child: Text(s('emoji_recent_empty'), style: TextStyle(color: context.lc.muted, fontSize: 13)),
              ),
            ),
          ),
        );
        continue;
      }
      slivers.add(
        SliverPadding(
          padding: const EdgeInsets.symmetric(horizontal: _kPad),
          sliver: SliverGrid(
            gridDelegate: SliverGridDelegateWithFixedCrossAxisCount(crossAxisCount: _cols, mainAxisExtent: _cell),
            delegate: SliverChildBuilderDelegate(
              (context, i) {
                final it = sec.items[i];
                return _EmojiCell(
                  item: it,
                  index: offset + i,
                  fontSize: fontSize,
                  cursor: _cursor,
                  onTap: () => _pick(it.char),
                  onHover: (on) {
                    if (on) {
                      _preview.value = it;
                    } else if (_preview.value == it && _cursor.value < 0) {
                      _preview.value = null;
                    }
                  },
                  onLongPress: (rect) {
                    if (it.base?.tones ?? false) {
                      _chooseTone(it, rect);
                    } else {
                      _showPeek(it, rect);
                    }
                  },
                  onLongPressEnd: _hidePeek,
                );
              },
              childCount: sec.items.length,
              addAutomaticKeepAlives: false,
            ),
          ),
        ),
      );
    }
    slivers.add(const SliverToBoxAdapter(child: SizedBox(height: 8)));
    return Focus(
      focusNode: _gridFocus,
      onKeyEvent: _onGridKey,
      onFocusChange: (f) {
        if (!f) _cursor.value = -1;
      },
      child: Scrollbar(
        controller: _scroll,
        child: CustomScrollView(controller: _scroll, slivers: slivers),
      ),
    );
  }

  Widget _gifPane(S s) => Center(
    child: Padding(
      padding: const EdgeInsets.all(24),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(AppIcons.gif, size: 40, color: context.lc.muted),
          const SizedBox(height: 8),
          Text(
            s('gif_privacy'),
            textAlign: TextAlign.center,
            style: TextStyle(color: context.lc.muted),
          ),
          if (widget.onGif != null) ...[
            const SizedBox(height: 12),
            FilledButton.tonalIcon(onPressed: widget.onGif, icon: const Icon(AppIcons.folder, size: 16), label: Text(s('gif_from_files'))),
          ],
        ],
      ),
    ),
  );

  Widget _stickerPane() {
    if (widget.onCustomSticker != null) {
      return Column(
        children: [
          Expanded(child: StickerPanel(onSend: widget.onCustomSticker!)),
          SizedBox(
            height: 52,
            child: ListView(
              scrollDirection: Axis.horizontal,
              padding: const EdgeInsets.symmetric(horizontal: 8),
              children: [
                for (final e in kStickers)
                  InkWell(
                    borderRadius: BorderRadius.circular(Radii.md),
                    onTap: () => (widget.onSticker ?? widget.onPick)(e),
                    child: Padding(
                      padding: const EdgeInsets.all(6),
                      child: Text(e, style: const TextStyle(fontSize: 30)),
                    ),
                  ),
              ],
            ),
          ),
        ],
      );
    }
    return GridView.builder(
      padding: const EdgeInsets.all(8),
      gridDelegate: const SliverGridDelegateWithMaxCrossAxisExtent(maxCrossAxisExtent: 76, mainAxisSpacing: 6, crossAxisSpacing: 6),
      itemCount: kStickers.length,
      itemBuilder: (context, i) => InkWell(
        borderRadius: BorderRadius.circular(Radii.md),
