class _EmojiCell extends StatelessWidget {
  const _EmojiCell({
    required this.item,
    required this.index,
    required this.fontSize,
    required this.cursor,
    required this.onTap,
    required this.onHover,
    required this.onLongPress,
    required this.onLongPressEnd,
  });
  final _Item item;
  final int index;
  final double fontSize;
  final ValueNotifier<int> cursor;
  final VoidCallback onTap;
  final ValueChanged<bool> onHover;
  final ValueChanged<Rect> onLongPress;
  final VoidCallback onLongPressEnd;

  Rect _rect(BuildContext context) {
    final box = context.findRenderObject() as RenderBox;
    return box.localToGlobal(Offset.zero) & box.size;
  }

  @override
  Widget build(BuildContext context) {
    final tones = item.base?.tones ?? false;
    return ValueListenableBuilder<int>(
      valueListenable: cursor,
      builder: (context, cur, child) => DecoratedBox(
        decoration: BoxDecoration(
          color: cur == index ? LC.primary.withValues(alpha: 0.18) : null,
          borderRadius: BorderRadius.circular(Radii.sm),
          border: cur == index ? Border.all(color: LC.primary.withValues(alpha: 0.7), width: 1.5) : null,
        ),
        child: child,
      ),
      child: Semantics(
        button: true,
        label: item.char,
        child: MouseRegion(
          onEnter: (_) => onHover(true),
          onExit: (_) => onHover(false),
          child: GestureDetector(
            onSecondaryTapUp: tones ? (_) => onLongPress(_rect(context)) : null,
            onLongPressStart: (_) {
              HapticFeedback.mediumImpact();
              onLongPress(_rect(context));
            },
            onLongPressEnd: (_) => onLongPressEnd(),
            onLongPressCancel: onLongPressEnd,
            child: InkWell(
              borderRadius: BorderRadius.circular(Radii.sm),
              onTap: onTap,
              canRequestFocus: false,
              child: Stack(
                children: [
                  Center(
                    child: Text(item.char, style: TextStyle(fontSize: fontSize, height: 1.15)),
                  ),
                  if (tones)
                    Positioned(
                      right: 4,
                      bottom: 4,
                      child: CustomPaint(size: const Size(5, 5), painter: _CornerMark(context.lc.muted.withValues(alpha: 0.55))),
                    ),
                ],
              ),
            ),
          ),
        ),
      ),
    );
  }
}

/// Tiny corner triangle: "long-press for skin tones".
class _CornerMark extends CustomPainter {
  _CornerMark(this.color);
  final Color color;
  @override
  void paint(Canvas canvas, Size size) {
    final p = Path()
      ..moveTo(size.width, 0)
      ..lineTo(size.width, size.height)
      ..lineTo(0, size.height)
      ..close();
    canvas.drawPath(p, Paint()..color = color);
  }

  @override
  bool shouldRepaint(_CornerMark old) => old.color != color;
}

