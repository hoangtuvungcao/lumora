/// Desktop: a floating emoji panel above [child] (the composer's emoji
/// button), like Telegram Desktop. Clicks outside close it.
class EmojiPopoverAnchor extends StatefulWidget {
  const EmojiPopoverAnchor({super.key, required this.open, required this.onClose, required this.builder, required this.child});
  final bool open;
  final VoidCallback onClose;
  final WidgetBuilder builder;
  final Widget child;

  static const size = Size(468, 430);

  @override
  State<EmojiPopoverAnchor> createState() => _EmojiPopoverAnchorState();
}

class _EmojiPopoverAnchorState extends State<EmojiPopoverAnchor> {
  final _link = LayerLink();
  final _portal = OverlayPortalController();
  final _group = Object();

  @override
  void initState() {
    super.initState();
    // The portal stays attached (empty while closed) so opening needs no
    // extra frame; show() can't be called during build.
    WidgetsBinding.instance.addPostFrameCallback((_) {
      if (mounted) _portal.show();
    });
  }

  @override
  Widget build(BuildContext context) {
    return CompositedTransformTarget(
      link: _link,
      child: OverlayPortal(
        controller: _portal,
        overlayChildBuilder: (context) => !widget.open
            ? const SizedBox.shrink()
            : CompositedTransformFollower(
                link: _link,
                targetAnchor: Alignment.topRight,
                followerAnchor: Alignment.bottomRight,
                offset: const Offset(44, -14),
                child: Align(
                  alignment: Alignment.bottomRight,
                  child: TapRegion(
                    groupId: _group,
                    onTapOutside: (_) => widget.onClose(),
                    child: CallbackShortcuts(
                      bindings: {const SingleActivator(LogicalKeyboardKey.escape): widget.onClose},
                      child: _PopoverCard(child: widget.builder(context)),
                    ),
                  ),
                ),
              ),
        child: TapRegion(groupId: _group, child: widget.child),
      ),
    );
  }
}

