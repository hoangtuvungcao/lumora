/// Shows the six skin tones of [base] above [anchor]; returns the tone
/// (0 = default yellow, 1..5) or null when dismissed.
Future<int?> showSkinTonePicker(BuildContext context, {required Emoji base, required Rect anchor, int current = 0}) {
  return Navigator.of(context).push<int>(_TonePopupRoute(base: base, anchor: anchor, current: current, barrierLabel: S.read(context)('emoji_skin_tone')));
}

class _TonePopupRoute extends PopupRoute<int> {
  _TonePopupRoute({required this.base, required this.anchor, required this.current, required this.barrierLabel});
  final Emoji base;
  final Rect anchor;
  final int current;

  @override
  final String barrierLabel;

  @override
  Color? get barrierColor => Colors.transparent;

  @override
  bool get barrierDismissible => true;

  @override
  Duration get transitionDuration => Motion.fast;

  @override
  Widget buildPage(BuildContext context, Animation<double> a, Animation<double> b) {
    final screen = MediaQuery.sizeOf(context);
    const cell = 44.0;
    const w = cell * 6 + 12 + 2; // + border
    const h = cell + 12 + 2;
    final left = (anchor.center.dx - w / 2).clamp(8.0, screen.width - w - 8);
    final above = anchor.top - h - 6;
    final top = above >= 8 ? above : anchor.bottom + 6;
    return Stack(
      children: [
        Positioned(
          left: left,
          top: top,
          width: w,
          height: h,
          child: FadeTransition(
            opacity: a,
            child: ScaleTransition(
              scale: Tween(begin: 0.9, end: 1.0).animate(CurvedAnimation(parent: a, curve: Motion.curve)),
              child: _FloatingCard(
                child: Padding(
                  padding: const EdgeInsets.all(6),
                  child: Row(
                    children: [
                      for (var t = 0; t <= 5; t++)
                        SizedBox(
                          width: cell,
                          height: cell,
                          child: Tooltip(
                            message: S.of(context)('skin_tone_$t'),
                            child: InkWell(
                              borderRadius: BorderRadius.circular(Radii.sm),
                              onTap: () => Navigator.pop(context, t),
                              child: Container(
                                decoration: t == current
                                    ? BoxDecoration(color: LC.primary.withValues(alpha: 0.18), borderRadius: BorderRadius.circular(Radii.sm))
                                    : null,
                                alignment: Alignment.center,
                                child: Text(base.withTone(t), style: const TextStyle(fontSize: 28, height: 1.15)),
                              ),
                            ),
                          ),
                        ),
                    ],
                  ),
                ),
              ),
            ),
          ),
        ),
      ],
    );
  }
}

