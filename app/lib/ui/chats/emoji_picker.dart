/// Full picker for reactions: a popover-sized dialog on desktop, a bottom
/// sheet on phones. Returns the chosen emoji.
Future<String?> pickEmoji(BuildContext context) {
  if (isDesktop(context)) {
    return showDialog<String>(
      context: context,
      barrierColor: Colors.black26,
      builder: (c) => Dialog(
        insetPadding: const EdgeInsets.all(24),
        clipBehavior: Clip.antiAlias,
        shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(Radii.lg)),
        child: SizedBox(
          width: EmojiPopoverAnchor.size.width,
          child: EmojiPicker(height: EmojiPopoverAnchor.size.height, showStickers: false, autofocusSearch: true, onPick: (e) => Navigator.pop(c, e)),
        ),
      ),
    );
  }
  return showModalBottomSheet<String>(
    context: context,
    showDragHandle: true,
    isScrollControlled: true,
    constraints: const BoxConstraints(maxWidth: 560),
    builder: (c) => SafeArea(
      child: Padding(
        padding: EdgeInsets.only(bottom: MediaQuery.viewInsetsOf(c).bottom),
        child: EmojiPicker(height: (MediaQuery.sizeOf(c).height * 0.55).clamp(320.0, 460.0), showStickers: false, onPick: (e) => Navigator.pop(c, e)),
      ),
    ),
  );
}

