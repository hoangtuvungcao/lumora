#!/usr/bin/env python3
"""Fetches the curated Noto Animated Emoji set as minified, gzipped Lottie.

Source: Google's Noto Animated Emoji (https://googlefonts.github.io/noto-emoji-animation/),
licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Attribution is shown in
Settings > About > Open-source licenses.

This runs at development time only. The app never fetches anything at runtime: both sides
of a chat render the animation from their own bundled copy, keyed by the emoji codepoints.

Usage: python3 tool/fetch_animated_emoji.py [--cache DIR]
Writes app/assets/emoji_anim/<key>.json.gz and lib/ui/chats/animated_emoji_set.dart, where
<key> is the lowercase hex codepoints without U+FE0F, joined by '_'.
"""
import argparse
import gzip
import json
import os
import sys
import urllib.request

# ~120 most-used emoji in chats (faces, hearts, hands, party, Tết, everyday) that exist in
# the Noto animated set. Order doesn't matter.
CURATED = (
    # faces
    '😀 😃 😄 😁 😆 😅 😂 🤣 😭 😉 😘 🥰 😍 🤩 🥳 🫠 🙃 🙂 🥲 🥹 😊 😌 😏 😋 😜 🤪 😔 🥺 😬 😐 '
    '🤐 🫡 🤔 🤫 🤭 🥱 🤗 🫣 😱 🤨 🙄 😮‍💨 😤 😡 🤬 😞 😢 😰 😮 😳 🤯 😩 🥴 🥵 🥶 🤮 😴 😷 😇 😎 '
    '🤡 💩 😈 👻 💀 🙈 '
    # hearts & sparkle
    '❤️ 🧡 💛 💚 💙 💜 🖤 🤍 🩷 💔 💖 💕 ❤️‍🔥 ✨ ⭐ 🔥 💯 '
    # hands
    '👍 👎 👏 🙏 👋 🙌 💪 🤝 👌 ✌️ 🤞 🫶 👀 '
    # party, Tết (fireworks, dragon, goat = 2027, apricot/peach blossom, mandarin) & everyday
    '🎉 🎊 🎂 🎁 🎈 🥂 🍻 🎆 🐉 🐐 🌸 🌼 🍊 🌹 💐 🍀 🌈 ☕ 🚀 🏆 ✅ ❌ 💡'
).split()

URL = 'https://fonts.gstatic.com/s/e/notoemoji/latest/{}/lottie.json'


def key_of(e):
    return '_'.join('%x' % ord(c) for c in e if ord(c) != 0xFE0F)


def round_floats(o, nd=3):
    if isinstance(o, float):
        r = round(o, nd)
        return int(r) if r == int(r) else r
    if isinstance(o, list):
        return [round_floats(x, nd) for x in o]
    if isinstance(o, dict):
        return {k: round_floats(v, nd) for k, v in o.items()}
    return o


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--cache', default=None, help='directory with downloaded lottie.json files')
    ap.add_argument('--api', required=True, help='path to the site\'s data/api.json (list of available emoji)')
    a = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    app = os.path.dirname(here)
    out = os.path.join(app, 'assets', 'emoji_anim')
    os.makedirs(out, exist_ok=True)
    avail = {x['codepoint'].replace('_fe0f', ''): x['codepoint'] for x in json.load(open(a.api))['icons']}
    seen, keys, total = set(), [], 0
    for e in CURATED:
        k = key_of(e)
        if k in seen:
            continue
        seen.add(k)
        if k not in avail:
            print('not animated upstream:', e, k, file=sys.stderr)
            continue
        raw = None
        cached = os.path.join(a.cache, k + '.json') if a.cache else None
        if cached and os.path.exists(cached):
            raw = open(cached, 'rb').read()
        else:
            with urllib.request.urlopen(URL.format(avail[k]), timeout=30) as r:
                raw = r.read()
            if cached:
                os.makedirs(a.cache, exist_ok=True)
                open(cached, 'wb').write(raw)
        data = round_floats(json.loads(raw))
        mini = json.dumps(data, separators=(',', ':'), ensure_ascii=True).encode()
        gz = gzip.compress(mini, 9, mtime=0)
        open(os.path.join(out, k + '.json.gz'), 'wb').write(gz)
        keys.append(k)
        total += len(gz)
    keys.sort()
    dart = os.path.join(app, 'lib', 'ui', 'chats', 'animated_emoji_set.dart')
    with open(dart, 'w', encoding='utf-8') as f:
        f.write('// GENERATED by tool/fetch_animated_emoji.py - do not edit.\n')
        f.write('// Noto Animated Emoji (c) Google, CC BY 4.0. %d animations, %d bytes gzipped.\n\n' % (len(keys), total))
        f.write('/// Keys (hex codepoints without FE0F, joined by "_") of the bundled animations\n')
        f.write('/// in `assets/emoji_anim/<key>.json.gz`.\n')
        f.write('const kAnimatedEmojiKeys = <String>{\n')
        for k in keys:
            f.write("  '%s',\n" % k)
        f.write('};\n')
    print('%d animations, %.2f MB gzipped' % (len(keys), total / 1e6))


if __name__ == '__main__':
    main()
